import * as THREE from "three";
import { MaterialOverrideConfig } from "../scene/types";

/**
 * Manages non-destructive material overrides, safe cloning, and original material restoration.
 */
export class ThreeDMaterialEngine {
  /**
   * Caches the original materials for each mesh in a scene object.
   * Maps mesh -> original material (or array of materials).
   */
  private static originalMaterialsRegistry = new WeakMap<
    THREE.Mesh,
    THREE.Material | THREE.Material[]
  >();

  /**
   * Tracks cloned materials created by overrides to enable safe memory disposal.
   */
  private static activeClones = new Set<THREE.Material>();

  /**
   * Registers all meshes under an object so their original materials can be restored later.
   */
  static registerOriginalMaterials(root: THREE.Object3D): void {
    root.traverse((child) => {
      if ((child as THREE.Mesh).isMesh) {
        const mesh = child as THREE.Mesh;
        if (!this.originalMaterialsRegistry.has(mesh) && mesh.material) {
          this.originalMaterialsRegistry.set(mesh, mesh.material);
        }
      }
    });
  }

  /**
   * Applies a non-destructive material override to matching meshes.
   * Clones materials on demand so shared materials are not polluted.
   */
  static applyOverride(root: THREE.Object3D, override: MaterialOverrideConfig): void {
    if (!override.enabled) {
      this.resetOverride(root);
      return;
    }

    // Ensure originals are recorded
    this.registerOriginalMaterials(root);

    const targetFilter = override.targetMeshName?.trim().toLowerCase();
    const applyToAll = !targetFilter || targetFilter === "all";

    root.traverse((child) => {
      if ((child as THREE.Mesh).isMesh) {
        const mesh = child as THREE.Mesh;
        const meshName = mesh.name.toLowerCase();

        if (applyToAll || meshName === targetFilter) {
          const original = this.originalMaterialsRegistry.get(mesh) || mesh.material;

          if (Array.isArray(original)) {
            const clonedArray = original.map((mat) => {
              const clone = this.cloneAndMutateMaterial(mat, override);
              this.activeClones.add(clone);
              return clone;
            });
            mesh.material = clonedArray;
          } else if (original instanceof THREE.Material) {
            const clone = this.cloneAndMutateMaterial(original, override);
            this.activeClones.add(clone);
            mesh.material = clone;
          }
        }
      }
    });
  }

  /**
   * Resets an object's meshes to their original materials and disposes cloned materials.
   */
  static resetOverride(root: THREE.Object3D): void {
    root.traverse((child) => {
      if ((child as THREE.Mesh).isMesh) {
        const mesh = child as THREE.Mesh;
        const original = this.originalMaterialsRegistry.get(mesh);
        if (original) {
          const currentMat = mesh.material;

          // Dispose of current cloned materials if they were generated by us
          if (Array.isArray(currentMat)) {
            for (const m of currentMat) {
              if (this.activeClones.has(m)) {
                m.dispose();
                this.activeClones.delete(m);
              }
            }
          } else if (currentMat instanceof THREE.Material) {
            if (this.activeClones.has(currentMat)) {
              currentMat.dispose();
              this.activeClones.delete(currentMat);
            }
          }

          mesh.material = original;
        }
      }
    });
  }

  /**
   * Helper that clones a single material and applies configuration overrides.
   */
  private static cloneAndMutateMaterial(
    src: THREE.Material,
    override: MaterialOverrideConfig
  ): THREE.Material {
    const clone = src.clone();

    // Standard / Physical material properties
    if (
      clone instanceof THREE.MeshStandardMaterial ||
      clone instanceof THREE.MeshPhysicalMaterial
    ) {
      if (override.color) {
        clone.color.set(override.color);
      }
      if (typeof override.roughness === "number") {
        clone.roughness = THREE.MathUtils.clamp(override.roughness, 0, 1);
      }
      if (typeof override.metalness === "number") {
        clone.metalness = THREE.MathUtils.clamp(override.metalness, 0, 1);
      }
      if (override.emissive) {
        clone.emissive.set(override.emissive);
      }
      if (typeof override.emissiveIntensity === "number") {
        clone.emissiveIntensity = override.emissiveIntensity;
      }
    }

    // Common material properties
    if (typeof override.opacity === "number") {
      clone.opacity = THREE.MathUtils.clamp(override.opacity, 0, 1);
    }
    if (typeof override.transparent === "boolean") {
      clone.transparent = override.transparent;
    }
    if (typeof override.wireframe === "boolean" && "wireframe" in clone) {
      (clone as any).wireframe = override.wireframe;
    }
    if (typeof override.doubleSided === "boolean") {
      clone.side = override.doubleSided ? THREE.DoubleSide : THREE.FrontSide;
    }

    clone.needsUpdate = true;
    return clone;
  }

  /**
   * Disposes all active cloned materials tracked by the engine.
   */
  static disposeAllClones(): void {
    for (const mat of this.activeClones) {
      mat.dispose();
    }
    this.activeClones.clear();
  }
}

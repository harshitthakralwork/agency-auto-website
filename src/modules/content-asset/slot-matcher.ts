// Maps component IDs to their required asset slots
export function getComponentSlotRequirements(componentId: string): AssetSlotRequirement[] {
  if (componentId === "hero-split" || componentId === "hero-centered") {
    return [SLOT_SPECIFICATIONS.HERO_BACKGROUND];
  }
  if (componentId === "hero-video") {
    return [SLOT_SPECIFICATIONS.HERO_BACKGROUND, SLOT_SPECIFICATIONS.POSTER_FALLBACK];
  }
  if (componentId === "hero-cinematic") {
    return [SLOT_SPECIFICATIONS.CANVAS_HERO_SEQUENCE, SLOT_SPECIFICATIONS.HERO_BACKGROUND];
  }
  if (componentId === "hero-3d") {
    return [SLOT_SPECIFICATIONS.THREE_D_HERO_MODEL];
  }
  if (componentId === "media-before-after-slider") {
    return [SLOT_SPECIFICATIONS.BEFORE_SLOT, SLOT_SPECIFICATIONS.AFTER_SLOT];
  }
  if (componentId === "media-gallery-grid" || componentId === "media-masonry-gallery") {
    return [SLOT_SPECIFICATIONS.GALLERY];
  }
  if (componentId === "advanced-canvas-frame-sequences") {
    return [SLOT_SPECIFICATIONS.CANVAS_HERO_SEQUENCE];
  }
  if (componentId === "advanced-interactive-3d-model" || componentId === "advanced-3d-product-showcase") {
    return [SLOT_SPECIFICATIONS.THREE_D_SHOWCASE_MODEL];
  }

  return [];
}

export class AssetSlotMatcher {
  /**
   * Matches available project assets against required component slots, generating fallbacks when missing.
   */
  public static matchSlot(
    requirement: AssetSlotRequirement,
    projectAssets: Array<{
      id: string;
      fileName: string;
      fileUrl: string;
      assetType: string;
      assignedSlot?: string | null;
      mimeType: string;
    }>,
    category = "healthcare",
    projectName = "Client Project"
  ): MatchedSlotResult {
    // Check if any asset is explicitly assigned to this slot
    const directMatch = projectAssets.find((a) => a.assignedSlot === requirement.slotName);

    if (directMatch) {
      return {
        slotName: requirement.slotName,
        required: requirement.required,
        status: "MATCHED",
        assetId: directMatch.id,
        assetUrl: directMatch.fileUrl,
        fileName: directMatch.fileName,
        mimeType: directMatch.mimeType,
      };
    }

    // Secondary heuristic: check if any unassigned asset matches allowedTypes
    const heuristicMatch = projectAssets.find(
      (a) => !a.assignedSlot && (requirement.allowedTypes as string[]).includes(a.assetType)
    );

    if (heuristicMatch) {
      return {
        slotName: requirement.slotName,
        required: requirement.required,
        status: "MATCHED",
        assetId: heuristicMatch.id,
        assetUrl: heuristicMatch.fileUrl,
        fileName: heuristicMatch.fileName,
        mimeType: heuristicMatch.mimeType,
      };
    }

    // Missing: generate SVG fallback token
    const fallbackDataUri = AssetFallbackGenerator.generateFallbackDataUri(
      requirement,
      category,
      projectName
    );

    return {
      slotName: requirement.slotName,
      required: requirement.required,
      status: "FALLBACK_GENERATED",
      fallbackSvgDataUri: fallbackDataUri,
    };
  }
}
